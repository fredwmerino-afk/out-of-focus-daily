// Out of Focus Daily: offline support.
// Pages: try the network first so updates show up right away; fall back to the saved copy offline.
// Paintings and icons: their file names never change, so use the saved copy when there is one.
const VERSION = "ofd-v1";
const CORE = ["/", "/index.html", "/site.css", "/how-to-play.html", "/about.html", "/privacy.html", "/contact.html",
              "/manifest.webmanifest", "/icons/icon-192.png", "/icons/icon-512.png"];

self.addEventListener("install", e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(CORE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== location.origin) return;   // leave ads, fonts and forms alone
  if (url.pathname.startsWith("/images/") || url.pathname.startsWith("/icons/")) {
    e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(res => {
      if (res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(req, copy)); }
      return res;
    })));
    return;
  }
  e.respondWith(fetch(req).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(VERSION).then(c => c.put(req, copy)); }
    return res;
  }).catch(() => caches.match(req, { ignoreSearch: true }).then(hit => hit || caches.match("/index.html"))));
});
